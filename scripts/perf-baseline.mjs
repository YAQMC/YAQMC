import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REQUIRED_METRICS = [
  ['coldStartInteractiveMs', 'Cold start to interactive (3 runs, median)'],
  ['warmStartInteractiveMs', 'Warm start to interactive'],
  ['rssBootIdle60sMiB', 'RSS after boot idle (60 s)'],
  ['rssPlayback30mMiB', 'RSS after 30 min playback'],
  ['cpuPausedPercent', 'CPU while paused'],
  ['cpuPlayingPercent', 'CPU while playing (idle UI)'],
  ['cpuSeekStormPercent', 'CPU during rapid-seek storm'],
  ['seekRoundTripP95Ms', 'Seek round-trip p95'],
  ['installerSizeMiB', 'Installer size'],
  ['installedSizeMiB', 'Installed size'],
];

const PLATFORMS = ['Windows', 'Linux'];

function usage() {
  return 'Usage: node scripts/perf-baseline.mjs [--input snapshot.json] [--output docs/migration/perf-baseline.md]';
}

function options(argv) {
  const result = {
    input: 'scripts/perf-baseline.snapshot.json',
    output: 'docs/migration/perf-baseline.md',
  };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--input' || argument === '--output') {
      const value = argv[index + 1];
      if (!value) throw new Error(`missing value for ${argument}`);
      result[argument.slice(2)] = value;
      index += 1;
    } else if (argument === '--help') {
      throw new Error(usage());
    } else {
      throw new Error(`unknown argument: ${argument}\n${usage()}`);
    }
  }
  return result;
}

function validateSnapshot(snapshot) {
  if (!snapshot || snapshot.schemaVersion !== 1) {
    throw new Error('snapshot must use schemaVersion 1');
  }
  for (const [metric] of REQUIRED_METRICS) {
    for (const platform of PLATFORMS) {
      const key = `${platform}:${metric}`;
      const measurement = snapshot.measurements?.[key];
      if (!measurement) throw new Error(`snapshot is missing required measurement ${key}`);
      if (measurement.state === 'pending') continue;
      if (measurement.state === 'measured' && Number.isFinite(measurement.value)) continue;
      throw new Error(`${key} must be pending or measured with a finite numeric value`);
    }
  }
  if (!Array.isArray(snapshot.toolchains) || !Array.isArray(snapshot.releaseAssets)) {
    throw new Error('snapshot must include toolchains and releaseAssets arrays');
  }
  if (!Array.isArray(snapshot.dataPaths) || !Array.isArray(snapshot.settingKeys)) {
    throw new Error('snapshot must include dataPaths and settingKeys arrays');
  }
  if (!snapshot.keyring?.service || !Array.isArray(snapshot.keyring.entries)) {
    throw new Error('snapshot must include keyring service and entries');
  }
  if (!Number.isInteger(snapshot.runtimeFacts?.registeredTauriCommands) || !snapshot.runtimeFacts?.mainWindow) {
    throw new Error('snapshot must include runtimeFacts');
  }
}

function formatMeasurement(measurement) {
  if (measurement.state === 'pending') return 'PENDING — manual measurement required';
  return String(measurement.value);
}

function table(rows) {
  return rows.map((row) => `| ${row.join(' | ')} |`).join('\n');
}

export function renderBaseline(snapshot) {
  validateSnapshot(snapshot);
  const lines = [
    '# Performance and artifact baseline',
    '',
    `Captured snapshot: ${snapshot.capturedAt}. This document is generated by \`npm run perf:baseline\` from \`scripts/perf-baseline.snapshot.json\`.`,
    '',
    'No pending item is an estimate or zero. It requires the documented manual protocol on a current Tauri build.',
    '',
    '## Toolchains and runtime facts',
    '',
    '| Toolchain | Required | Observed in baseline environment | State |',
    '|---|---|---|---|',
    table(snapshot.toolchains.map((toolchain) => [toolchain.name, toolchain.required, toolchain.observed, toolchain.state.toUpperCase()])),
    '',
    '| Runtime fact | Value |',
    '|---|---|',
    table([
      ['Registered Tauri commands', String(snapshot.runtimeFacts.registeredTauriCommands)],
      ['Main window target', snapshot.runtimeFacts.mainWindow],
    ]),
    '',
    '## Manual performance and size measurements',
    '',
    'Protocol: use three clean cold starts and report their median; measure warm start separately; sum the host processes for RSS and CPU. Collect all rows on the Windows and Linux primary development machines before treating this baseline as a release gate.',
    '',
    '| Metric | Windows | Linux |',
    '|---|---|---|',
    table(
      REQUIRED_METRICS.map(([metric, label]) => [
        label,
        formatMeasurement(snapshot.measurements[`Windows:${metric}`]),
        formatMeasurement(snapshot.measurements[`Linux:${metric}`]),
      ]),
    ),
    '',
    '## Current release artifacts',
    '',
    '| Platform | Architectures | Formats |',
    '|---|---|---|',
    table(snapshot.releaseAssets.map((asset) => [asset.platform, asset.architectures, asset.formats])),
    '',
    'These are current Tauri artifacts. No Electron asset is introduced by this baseline task; the compatibility matrix remains in `docs/migration/release-assets.md`.',
    '',
    '## Data continuity facts',
    '',
    '| Platform | Purpose | Resolved path | Evidence state |',
    '|---|---|---|---|',
    table(snapshot.dataPaths.map((dataPath) => [dataPath.platform, dataPath.purpose, dataPath.path, dataPath.state.toUpperCase()])),
    '',
    `Persisted setting keys: ${snapshot.settingKeys.map((key) => `\`${key}\``).join(', ')}.`,
    '',
    `Keyring service: \`${snapshot.keyring.service}\`; entries: ${snapshot.keyring.entries.map((entry) => `\`${entry}\``).join(', ')}.`,
    '',
    'The path values above are source-verified expectations. Export and attach a live Tauri diagnostics snapshot on Windows and Linux to promote each platform/path row to live-verified.',
    '',
  ];
  return lines.join('\n');
}

function invokedDirectly() {
  return Boolean(process.argv[1]) && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
}

if (invokedDirectly()) {
  try {
    const { input, output } = options(process.argv.slice(2));
    const snapshot = JSON.parse(readFileSync(input, 'utf8'));
    writeFileSync(output, renderBaseline(snapshot));
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
